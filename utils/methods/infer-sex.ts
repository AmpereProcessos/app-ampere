// Sufixos com forte predominância de um dos sexos em nomes brasileiros,
// aplicados apenas quando o nome não consta nas listas acima.
const MALE_SUFFIXES = ["SON", "TON", "LDO", "RDO", "CIO", "RIO", "LIO", "AEL", "IEL", "UEL", "EUS", "AIR", "MIR", "MAR"];
const FEMALE_SUFFIXES = ["INHA", "ELLE", "ELLY", "IANE", "IANA", "LENE", "EIDE", "ICE"];

function normalizeFirstName(fullName: string) {
  return (
    fullName
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .trim()
      .toUpperCase()
      .split(/\s+/)[0] ?? ""
  );
}

export function inferSexFromName(fullName?: string | null): TInferredSex {
  if (!fullName) return "INDETERMINADO";
  const firstName = normalizeFirstName(fullName);
  // Nomes muito curtos, siglas ou razões sociais não são classificáveis
  if (firstName.length < 3 || /[^A-Z]/.test(firstName)) return "INDETERMINADO";

  if (MALE_NAMES.has(firstName)) return "MASCULINO";
  if (FEMALE_NAMES.has(firstName)) return "FEMININO";

  if (FEMALE_SUFFIXES.some((suffix) => firstName.endsWith(suffix))) return "FEMININO";
  if (MALE_SUFFIXES.some((suffix) => firstName.endsWith(suffix))) return "MASCULINO";

  // Terminações gerais: "A" é majoritariamente feminino e "O"/"R"/"S" masculino
  if (firstName.endsWith("A")) return "FEMININO";
  if (firstName.endsWith("O")) return "MASCULINO";

  return "INDETERMINADO";
}
